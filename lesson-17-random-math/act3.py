import math
print('The Floor and ceiling value of 57.98 are:'+str(math.ceil(57.98)) +','+ str(math.floor(57.98)))

x = 10
y = - 15
# Using Copysign function
print('The value of x after copying  the sign of y is:'+str(math.copysign(x,y)))

# using fabs and gcd functions
print('The absolute value of -97 and 65 are:'+str(math.fabs(-97.25)) + ','+ str (math.fabs(65)))

print('The greatest common divisor of 24 and 56 :'+str(math.gcd(24,56)))
